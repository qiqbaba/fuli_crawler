# -*- coding: utf-8 -*-
"""从任务日志中抽取结构化业务指标。

旧版 Streamlit 工作台在页面内直接调用 fixes/* 并截获 stdout，因此可以把日志
正则抽成指标卡；新版任务跑在子进程里，只能看到纯文本日志。这里复用同一套
正则思路，按顺序尝试并把命中的数值整理成 {label, value} 列表，供前端渲染。
"""
from __future__ import annotations

import re
from typing import Any, Dict, List, Tuple

MAX_METRICS = 6

# (标签, 正则, 单位) —— 顺序即优先级，先命中的标签优先展示
_PATTERNS: Tuple[Tuple[str, str, str], ...] = (
    # ---------- PDF 维护 / 去重 ----------
    ("待清理冗余文件", r"待清理冗余文件数\s*[:：]\s*([\d,]+)", "个"),
    ("待清理死链", r"待清理死链记录总数\s*[:：]\s*([\d,]+)", "条"),
    ("待清理记录", r"待清理记录数\s*[:：]\s*([\d,]+)", "条"),
    ("预估释放空间", r"预估可释放磁盘空间\s*[:：]\s*([^\n\r,，)]+)", ""),
    ("冗余空间", r"冗余空间\s*[:：]\s*([^\n\r,，)]+)", ""),
    ("待去重组数", r"待(?:处理|归类)去重组数\s*[:：]\s*([\d,]+)", "组"),
    ("完全重复组", r"共发现\s*([\d,]+)\s*组完全重复", "组"),
    ("同名变体组", r"发现\s*([\d,]+)\s*组同名/标题变体", "组"),
    ("重复组数", r"发现\s*([\d,]+)\s*组重复记录", "组"),
    ("物理丢失死链", r"物理文件丢失的数据库死[链标记]*记录数\s*[:：]\s*([\d,]+)", "条"),
    ("物理扫描文件", r"物理文件扫描完成.*?发现\s*([\d,]+)\s*个\s*PDF", "个"),
    ("孤立文件", r"(?:共找到|扫描到)\s*([\d,]+)\s*个孤立", "个"),
    ("待关联文件", r"待关联\s*([\d,]+)\s*个", "个"),
    ("成功关联", r"成功关联\s*([\d,]+)\s*个", "个"),
    ("番号记录", r"(?:识别出|共找到)\s*([\d,]+)\s*条.*?番号", "条"),
    ("缺失 PDF", r"缺失\s*([\d,]+)\s*条.*?PDF", "条"),
    ("处理记录", r"共处理\s*([\d,]+)\s*条", "条"),
    ("缓存命中", r"命中\s*([\d,]+)\s*条", "条"),
    ("扫描记录", r"读取\s*([\d,]+)\s*条记录", "条"),
    # ---------- 日期比对审计 ----------
    ("物理文件总数", r"物理文件总数\s*[:：]\s*([\d,]+)", "个"),
    ("日期一致", r"正常一致文件数\s*[:：]\s*([\d,]+)", "个"),
    ("日期不符", r"日期不符文件数[^:：]*[:：]\s*([\d,]+)", "个"),
    ("多重冲突", r"多重匹配冲突[^:：]*[:：]\s*([\d,]+)", "个"),
    # ---------- 云端监控 ----------
    ("Supabase 记录数", r"Supabase.*?总记录数[:：]\s*([\d,]+)", ""),
    ("Supabase 表大小", r"(?:表大小 \(RPC\)|估算表大小)\s*[:：]\s*~?([^\n\r(]+)", ""),
    ("R2 文件总数", r"PDF 文件总数[:：]\s*([\d,]+)", ""),
    ("R2 总占用", r"PDF 总大小[:：]\s*([^\n\r(]+)", ""),
    ("DynamoDB 记录数", r"(?:近似|精确)记录数[:：]\s*([\d,]+)", ""),
    # ---------- Supabase 同步 / 清理 ----------
    ("云端读取", r"云端读取总数\s*[:：]\s*([\d,]+)", "条"),
    ("本地新增", r"本地新增合并数\s*[:：]\s*([\d,]+)", "条"),
    ("重复忽略", r"本地重复忽略数\s*[:：]\s*([\d,]+)", "条"),
    ("云端扫描", r"云端扫描总数\s*[:：]\s*([\d,]+)", "条"),
    ("本地已归档", r"本地已归档\(可清理\)\s*[:：]\s*([\d,]+)", "条"),
    ("受保护记录", r"本地未归档\(受保护\)\s*[:：]\s*([\d,]+)", "条"),
    # ---------- R2 下载 / 清理 ----------
    ("候选对象", r"找到\s*([\d,]+)\s*个文件", "个"),
    ("成功", r"^\s*(?:✅\s*)?成功\s*[:：]\s*([\d,]+)", "个"),
    ("下载成功", r"下载成功\s*[:：]\s*([\d,]+)", "个"),
    ("断点跳过", r"跳过\s*[:：]\s*([\d,]+)", "个"),
    ("失败", r"^\s*(?:❌\s*)?失败\s*[:：]\s*([\d,]+)", "个"),
    ("传输体积", r"总大小\s*[:：]\s*([^\n\r]+)", ""),
    # ---------- DynamoDB ----------
    ("本地有效记录", r"本地共有\s*([\d,]+)\s*条有效 URL", "条"),
    ("云端已有记录", r"云端现有\s*([\d,]+)\s*条记录", "条"),
    ("待增量上传", r"云端缺失的记录\s*[:：]\s*([\d,]+)\s*条", "条"),
    ("成功写入", r"成功写入\s*[:：]?\s*([\d,]+)", ""),
    ("去重键", r"共生成\s*([\d,]+)\s*个独立的相对路径去重键", "个"),
    # ---------- 导出 ----------
    ("导出 URL", r"读取 URL\s*([\d,]+)\s*条", "条"),
    ("导出磁力", r"磁力链接\s*([\d,]+)\s*条", "条"),
)


def extract_metrics(lines: List[str]) -> List[Dict[str, Any]]:
    """从日志行中提取指标；命中上限或没有命中时返回空列表。"""
    if not lines:
        return []
    text = "\n".join(lines)
    results: List[Dict[str, Any]] = []
    seen = set()
    for label, pattern, unit in _PATTERNS:
        if len(results) >= MAX_METRICS:
            break
        if label in seen:
            continue
        match = re.search(pattern, text, re.MULTILINE)
        if not match:
            continue
        raw = match.group(1).strip().strip("，,。")
        if not raw:
            continue
        seen.add(label)
        results.append({"label": label, "value": f"{raw} {unit}".strip()})
    return results
